import assert from "node:assert/strict";
import { webcrypto } from "node:crypto";
import { parseSignedEpub, handleSignedEpubReader } from "../cloudflare/runner3-core/src/ebook-signed-reader.js";

globalThis.crypto ||= webcrypto;
const origin = "https://runner3-core.example.com";
const key = "/delivery/ebook/bataille-test/final/Foreword.vi.epub";
const secret = "test-only-no-real-secrets";
const now = Math.floor(Date.now()/1000);
const exp = now + 3600;
const derive = await crypto.subtle.digest("SHA-256",new TextEncoder().encode("runner3-delivery-v1\n"+secret));
const signer = await crypto.subtle.importKey("raw",derive,{name:"HMAC",hash:"SHA-256"},false,["sign"]);
const sigBytes = new Uint8Array(await crypto.subtle.sign("HMAC",signer,new TextEncoder().encode("GET\n"+key+"\n"+exp)));
const sig = Buffer.from(sigBytes).toString("base64url");
const delivery = origin+key+"?exp="+exp+"&sig="+sig;
const url = origin+"/artifact-library/read-signed?file="+encodeURIComponent(delivery);
const parsed = parseSignedEpub(url,now);
assert.equal(parsed?.name,"Foreword.vi.epub");
assert.equal(parsed?.key,"core/ebook/bataille-test/final/Foreword.vi.epub");
assert.equal(parseSignedEpub(url,exp+1),null,"expired");
assert.equal(parseSignedEpub(url+"&another=1",now),null,"extra query");
assert.equal(parseSignedEpub(origin+"/artifact-library/read-signed?file="+encodeURIComponent("https://evil.example/"+key.slice(1)+"?exp="+exp+"&sig="+sig),now),null,"cross-origin");
assert.equal(parseSignedEpub(origin+"/artifact-library/read-signed?file="+encodeURIComponent(origin+"/delivery/ebook/bataille-test/work/Foreword.vi.epub?exp="+exp+"&sig="+sig),now),null,"work not final");
assert.equal(parseSignedEpub(origin+"/artifact-library/read-signed?file="+encodeURIComponent(origin+"/delivery/other/bataille-test/final/Foreword.vi.epub?exp="+exp+"&sig="+sig),now),null,"other project");
const env = {RUNNER3_CORE_TOKEN:secret, ARTIFACTS:{head:async p=>p==="core/ebook/bataille-test/final/Foreword.vi.epub"?{size:52000,httpMetadata:{contentType:"application/epub+zip"}}:null}};
const result = await handleSignedEpubReader(new Request(url),env);
assert.equal(result.status,200,"valid signature and R2 object can read");
const html = await result.text();
assert.match(html,/epub\.min\.js/);
assert.match(html,/Đọc không cần PIN/);
assert.equal(result.headers.get("Referrer-Policy"),"no-referrer");
assert.match(result.headers.get("X-Robots-Tag"),/noindex/);
const tampered = url.replace(/sig%3D[A-Za-z0-9_-]+/, "sig%3D"+("A".repeat(43)));
const denied = await handleSignedEpubReader(new Request(tampered),env);
assert.equal(denied.status,403,"invalid HMAC cannot access content");
const unsupported = await handleSignedEpubReader(new Request(url,{method:"POST"}),env);
assert.equal(unsupported.status,405);
