import fs from 'fs';
import { build } from 'esbuild';

const outfile='/tmp/runner3wp-rum-client.js';
const moduleOut='edge/wordpress-edge-proxy/src/rum-client.generated.js';
const source=`
import {onCLS,onFCP,onINP,onLCP,onTTFB} from 'web-vitals/attribution';
const endpoint='/__runner3/rum';
function targetOf(m){const a=m.attribution||{};return String(a.target||a.largestShiftTarget||a.interactionTarget||'').slice(0,180)}
function send(m){
  try{
    const p={name:m.name,value:m.value,delta:m.delta,rating:m.rating,id:m.id,path:location.pathname.slice(0,500),target:targetOf(m),nav:String(m.navigationType||'').slice(0,40),connection:String(navigator.connection?.effectiveType||'').slice(0,20),vw:innerWidth||0,dpr:devicePixelRatio||1};
    const b=JSON.stringify(p); if(navigator.sendBeacon) navigator.sendBeacon(endpoint,new Blob([b],{type:'application/json'})); else fetch(endpoint,{method:'POST',headers:{'content-type':'application/json'},body:b,keepalive:true,credentials:'omit'}).catch(()=>{});
  }catch{}
}
onCLS(send);onFCP(send);onINP(send);onLCP(send);onTTFB(send);
`;
await build({stdin:{contents:source,resolveDir:process.cwd(),sourcefile:'runner3wp-rum-entry.js'},bundle:true,minify:true,format:'iife',platform:'browser',target:['es2020'],outfile,legalComments:'none'});
const js=fs.readFileSync(outfile,'utf8');
fs.writeFileSync(moduleOut,`// Generated by scripts/build-runner3wp-rum-client.mjs\nexport const RUM_CLIENT = ${JSON.stringify(js)};\n`);
console.log(JSON.stringify({status:'ready',bytes:Buffer.byteLength(js),outfile,moduleOut},null,2));
